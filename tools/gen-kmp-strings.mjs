#!/usr/bin/env node
// #321 step 5: generates velta-kmp LangRu.kt / LangFr.kt from the REAL web
// packs (app/locales/*.json — English string is the key, i18n.js:41-47),
// filtered to the L.t("…") keys the KMP client actually uses. The web ships
// all 1655 keys; the KMP client only needs its own call sites, and a key the
// packs do not have is a PORTING BUG (the web string casing drifted) —
// report mode lists them, tests/kmp-strings.test.mjs fails CI on both
// staleness and missing keys.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

// commonMain AND androidMain: notification channels, the lock prompt and
// the sync service call L.t too (#334).
const SRCS = ["velta-kmp/composeApp/src/commonMain/kotlin", "velta-kmp/composeApp/src/androidMain/kotlin"];
const OUT = "velta-kmp/composeApp/src/commonMain/kotlin/org/velta/kmp/ui";

const esc = (s) => JSON.stringify(s).replace(/\$/g, "\\$");

const GENERATED = new Set(["LangRu.kt", "LangFr.kt"]);

/** Kotlin source of every .kt file (the generated packs excluded — their
 *  keys would feed themselves back in), whole-line // comments stripped
 *  (headers mention L.t("…")). */
function sources() {
  const out = [];
  const walk = (dir) => {
    for (const f of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, f.name);
      if (f.isDirectory()) walk(p);
      else if (f.name.endsWith(".kt") && !GENERATED.has(f.name)) {
        out.push(readFileSync(p, "utf8").replace(/^[ \t]*\/\/[^\n]*/gm, ""));
      }
    }
  };
  for (const src of SRCS) walk(src);
  return out;
}

/** Kotlin escapes (\" \\ \n \$) → the real string, or null if unparsable. */
function unescape(body) {
  try {
    return JSON.parse(`"${body.replace(/\\\$/g, "$")}"`);
  } catch {
    return null;
  }
}

/** Every L.t("…") literal: these MUST exist in a pack. */
export function usedKeys() {
  const keys = new Set();
  for (const src of sources()) {
    for (const m of src.matchAll(/\bL\.t\("((?:[^"\\]|\\.)*)"\)/g)) {
      const k = unescape(m[1]);
      if (k != null) keys.add(k);
    }
  }
  return [...keys];
}

/** Every plain string literal (no ${} template). Labels picked by a
 *  `when`, kept in rule tables or passed through L.t(variable) are not
 *  literal L.t calls; a literal that IS a pack key is shipped too, so
 *  those translate instead of silently staying English (#334 step 9). */
export function literalStrings() {
  const out = new Set();
  for (const src of sources()) {
    for (const m of src.matchAll(/"((?:[^"\\\n]|\\.)*)"/g)) {
      if (/(^|[^\\])\$\{/.test(m[1]) || /(^|[^\\])\$[a-zA-Z]/.test(m[1])) continue;
      const k = unescape(m[1]);
      if (k != null && /[A-Za-z]/.test(k)) out.add(k);
    }
  }
  return out;
}

/** KMP-only strings (screens stable does not have): velta-kmp/i18n/<lang>.json.
 *  English is the key, like the web packs; a key the web pack already has
 *  belongs THERE (tests/kmp-strings.test.mjs). */
export function kmpPack(lang) {
  return JSON.parse(readFileSync(join("velta-kmp/i18n", `${lang}.json`), "utf8"));
}

const FILE_FOR = { ru: "LangRu.kt", fr: "LangFr.kt" };
const OBJ_FOR = { ru: "LangRu", fr: "LangFr" };

export function generateKmpStrings() {
  const used = usedKeys();
  const literals = literalStrings();
  const out = {};
  const missing = {};
  let keys = used;
  for (const lang of ["ru", "fr"]) {
    const web = JSON.parse(readFileSync(join("app/locales", `${lang}.json`), "utf8"));
    const pack = { ...kmpPack(lang), ...web };
    const has = (k) => typeof pack[k] === "string" && pack[k] !== "";
    missing[lang] = used.filter((k) => !has(k));
    keys = [...new Set([...used, ...[...literals].filter(has)])];
    const entries = keys
      .filter(has)
      .sort()
      .map((k) => `        ${esc(k)} to ${esc(pack[k])},`)
      .join("\n");
    out[FILE_FOR[lang]] = `package org.velta.kmp.ui

// GENERATED by tools/gen-kmp-strings.mjs from app/locales/${lang}.json and
// velta-kmp/i18n/${lang}.json (KMP-only screens) — do not hand-edit.
// Filtered to the keys this client uses (English string = key, i18n.js).

internal object ${OBJ_FOR[lang]} {
    val MAP: Map<String, String> = mapOf(
${entries}
    )
}
`;
  }
  return { files: out, keys, missing };
}

if (process.env.VELTA_GEN_NO_WRITE !== "1") {
  const { files, keys, missing } = generateKmpStrings();
  for (const [name, body] of Object.entries(files)) writeFileSync(join(OUT, name), body);
  for (const lang of Object.keys(missing)) {
    if (missing[lang].length) {
      console.error(`[${lang}] keys missing from app/locales/${lang}.json:`);
      for (const k of missing[lang]) console.error(`  - ${JSON.stringify(k)}`);
    }
  }
  console.log(`gen-kmp-strings: ${keys.length} keys x ${Object.keys(files).length} packs written`);
  if (missing.ru.length || missing.fr.length) process.exitCode = 1;
}
