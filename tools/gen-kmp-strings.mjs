#!/usr/bin/env node
// #321 step 5: generates velta-kmp LangRu.kt / LangFr.kt from the REAL web
// packs (app/locales/*.json — English string is the key, i18n.js:41-47),
// filtered to the L.t("…") keys the KMP client actually uses. The web ships
// all 1655 keys; the KMP client only needs its own call sites, and a key the
// packs do not have is a PORTING BUG (the web string casing drifted) —
// report mode lists them, tests/kmp-strings.test.mjs fails CI on both
// staleness and missing keys.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const SRC = "velta-kmp/composeApp/src/commonMain/kotlin";
const OUT = "velta-kmp/composeApp/src/commonMain/kotlin/org/velta/kmp/ui";

const esc = (s) => JSON.stringify(s).replace(/\$/g, "\\$");

/** Every L.t("…") literal in commonMain. */
export function usedKeys() {
  const keys = new Set();
  const walk = (dir) => {
    for (const f of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, f.name);
      if (f.isDirectory()) walk(p);
      else if (f.name.endsWith(".kt")) {
        // Strip whole-line // comments FIRST — the generated files' own
        // headers mention L.t("…") and would otherwise feed themselves
        // back in as a "used key".
        const src = readFileSync(p, "utf8").replace(/^[ \t]*\/\/[^\n]*/gm, "");
        for (const m of src.matchAll(/\bL\.t\("((?:[^"\\]|\\.)*)"\)/g)) keys.add(m[1]);
      }
    }
  };
  walk(SRC);
  return [...keys];
}

const FILE_FOR = { ru: "LangRu.kt", fr: "LangFr.kt" };
const OBJ_FOR = { ru: "LangRu", fr: "LangFr" };

export function generateKmpStrings() {
  const keys = usedKeys();
  const out = {};
  const missing = {};
  for (const lang of ["ru", "fr"]) {
    const pack = JSON.parse(readFileSync(join("app/locales", `${lang}.json`), "utf8"));
    missing[lang] = keys.filter((k) => !(k in pack) || typeof pack[k] !== "string" || pack[k] === "");
    const entries = keys
      .filter((k) => typeof pack[k] === "string" && pack[k] !== "")
      .sort()
      .map((k) => `        ${esc(k)} to ${esc(pack[k])},`)
      .join("\n");
    out[FILE_FOR[lang]] = `package org.velta.kmp.ui

// GENERATED by tools/gen-kmp-strings.mjs from app/locales/${lang}.json — do
// not hand-edit. Filtered to the L.t("…") keys this client uses; the web
// pack ships all of them (English string = key, i18n.js).

internal object ${OBJ_FOR[lang]} {
    val MAP: Map<String, String> = mapOf(
${entries}
    )
}
`;
  }
  return { files: out, keys, missing };
}

if (process.env.VELTA_GEN_NO_WRITE !== "1") {
  const { files, keys, missing } = generateKmpStrings();
  for (const [name, body] of Object.entries(files)) writeFileSync(join(OUT, name), body);
  for (const lang of Object.keys(missing)) {
    if (missing[lang].length) {
      console.error(`[${lang}] keys missing from app/locales/${lang}.json:`);
      for (const k of missing[lang]) console.error(`  - ${JSON.stringify(k)}`);
    }
  }
  console.log(`gen-kmp-strings: ${keys.length} keys x ${Object.keys(files).length} packs written`);
  if (missing.ru.length || missing.fr.length) process.exitCode = 1;
}
