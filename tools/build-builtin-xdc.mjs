#!/usr/bin/env node
// Builds the built-in webxdc apps shipped with Velta (#138 part 2):
//   app/webxdc/send-direct/  ->  app/builtin/send-direct.xdc
// main.js = transfer.js (ES module, node-tested) rewritten as a classic
// script exposing window.Transfer, then ui.js. The .xdc is a STORE-only
// zip with fixed timestamps so the output is byte-reproducible;
// tests/send-direct-xdc.test.mjs rebuilds it in memory and fails when the
// committed file is stale. Run: node tools/build-builtin-xdc.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";

const root = fileURLToPath(new URL("..", import.meta.url));

const CRC = new Uint32Array(256).map((_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
export function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

export function zipStore(entries) {
  const locals = [];
  const centrals = [];
  let offset = 0;
  for (const { name, data } of entries) {
    const n = Buffer.from(name, "utf8");
    const crc = crc32(data);
    const lh = Buffer.alloc(30);
    lh.writeUInt32LE(0x04034b50, 0); lh.writeUInt16LE(20, 4); lh.writeUInt16LE(0x0800, 6);
    lh.writeUInt16LE(0, 8); lh.writeUInt16LE(0, 10); lh.writeUInt16LE(0x21, 12); // 1980-01-01
    lh.writeUInt32LE(crc, 14); lh.writeUInt32LE(data.length, 18); lh.writeUInt32LE(data.length, 22);
    lh.writeUInt16LE(n.length, 26); lh.writeUInt16LE(0, 28);
    locals.push(lh, n, data);
    const ch = Buffer.alloc(46);
    ch.writeUInt32LE(0x02014b50, 0); ch.writeUInt16LE(20, 4); ch.writeUInt16LE(20, 6); ch.writeUInt16LE(0x0800, 8);
    ch.writeUInt16LE(0, 10); ch.writeUInt16LE(0, 12); ch.writeUInt16LE(0x21, 14);
    ch.writeUInt32LE(crc, 16); ch.writeUInt32LE(data.length, 20); ch.writeUInt32LE(data.length, 24);
    ch.writeUInt16LE(n.length, 28); ch.writeUInt32LE(offset, 42);
    centrals.push(ch, n);
    offset += 30 + n.length + data.length;
  }
  const cd = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, cd, end]);
}

// Legacy 64x64 placeholder (unused since the Velta Beam icon.svg/png): accent tile with a white right-pointing arrow (no image deps).
export function iconPng() {
  const W = 64;
  const raw = Buffer.alloc((W * 4 + 1) * W);
  for (let y = 0; y < W; y++) {
    raw[y * (W * 4 + 1)] = 0;
    for (let x = 0; x < W; x++) {
      const o = y * (W * 4 + 1) + 1 + x * 4;
      const shaft = x >= 14 && x < 38 && y >= 27 && y < 37;
      const head = x >= 36 && x < 52 && Math.abs(y - 32) <= (52 - x);
      const white = shaft || head;
      raw[o] = white ? 255 : 0x3d; raw[o + 1] = white ? 255 : 0x8b; raw[o + 2] = white ? 255 : 0xfd; raw[o + 3] = 255;
    }
  }
  const chunk = (type, data) => {
    const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
    const td = Buffer.concat([Buffer.from(type), data]);
    const c = Buffer.alloc(4); c.writeUInt32BE(crc32(td));
    return Buffer.concat([len, td, c]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(W, 0); ihdr.writeUInt32BE(W, 4); ihdr[8] = 8; ihdr[9] = 6;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })), chunk("IEND", Buffer.alloc(0))]);
}

export function classicTransfer(src) {
  const names = [...src.matchAll(/^export (?:const|function|class) ([A-Za-z_$][\w$]*)/gm)].map(m => m[1]);
  const extra = [...src.matchAll(/^export const [^;]*;/gm)].flatMap(m => [...m[0].matchAll(/,\s*([A-Za-z_$][\w$]*)\s*=/g)].map(x => x[1]));
  const body = src.replace(/^export /gm, "");
  return `// generated by tools/build-builtin-xdc.mjs from transfer.js — do not edit\n(function () {\n"use strict";\n${body}\nwindow.Transfer = { ${[...new Set([...names, ...extra])].join(", ")} };\n})();\n`;
}

export function buildSendDirect(icon) {
  const dir = `${root}app/webxdc/send-direct/`;
  const read = (f) => readFileSync(dir + f);
  const main = classicTransfer(read("transfer.js").toString("utf8")) + read("ui.js").toString("utf8");
  return zipStore([
    { name: "manifest.toml", data: read("manifest.toml") },
    { name: "index.html", data: read("index.html") },
    { name: "velta-tokens.css", data: read("velta-tokens.css") },
    { name: "main.js", data: Buffer.from(main, "utf8") },
    { name: "icon.png", data: icon || read("icon.png") },
  ]);
}

// Group calls (docs/agents/group-calls.md): UI-only app; the host runs the
// call for it once its bundle hash is on the trusted list below.
export function buildGroupCall() {
  const dir = `${root}app/webxdc/group-call/`;
  const read = (f) => readFileSync(dir + f);
  return zipStore([
    { name: "manifest.toml", data: read("manifest.toml") },
    { name: "index.html", data: read("index.html") },
    { name: "velta-tokens.css", data: read("velta-tokens.css") },
    { name: "main.js", data: read("main.js") },
    { name: "icon.png", data: read("icon.png") },
  ]);
}

// Velta design tokens for the built-in webxdc apps (Beam, Circle). A webxdc
// cannot load Velta's CSS, so every .xdc bundles its own velta-tokens.css,
// generated here from app/css/main.css (dark :root + light theme block) and
// committed next to each app; tests/design-token-guard.test.mjs fails when a
// copy drifts from main.css. Dark/light follow prefers-color-scheme; inside
// Velta, Circle additionally gets the host's live tokens (getTheme()).
export const XDC_TOKEN_APPS = ["send-direct", "group-call"];
export const XDC_COLOR_TOKENS = ["--bg", "--bg-sidebar", "--bg-hover", "--bg-active", "--bg-bubble-in", "--accent", "--accent-hover",
  "--on-accent", "--accent-text", "--text", "--text-dim", "--green", "--danger", "--border", "--shadow"];
export const XDC_SIZE_TOKENS = ["--radius-bubble", "--radius-media", "--radius-quote", "--msg-font-size"];
function cssBlock(css, selector) {
  const i = css.indexOf(selector + " {");
  if (i < 0) throw new Error("main.css: no " + selector + " block");
  const body = css.slice(i + selector.length + 2, css.indexOf("\n}", i));
  const out = {};
  for (const m of body.replace(/\/\*[\s\S]*?\*\//g, "").matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)) out[m[1]] = m[2].trim();
  return out;
}
export function xdcTokensCss(mainCss = readFileSync(`${root}app/css/main.css`, "utf8")) {
  const dark = cssBlock(mainCss, ":root"), light = cssBlock(mainCss, 'html[data-theme="light"]');
  const decl = (map, keys, pad) => keys.filter((k) => map[k] != null).map((k) => `${pad}${k}: ${map[k]};`).join("\n");
  return `/* Generated by tools/build-builtin-xdc.mjs from app/css/main.css — do not edit.
   Velta design-system tokens (design/velta-design-system.html) for webxdc apps. */
:root {
${decl(dark, [...XDC_COLOR_TOKENS, ...XDC_SIZE_TOKENS], "  ")}
  /* spacing / type / shape scale (main.css has no spacing tokens; these are the
     design-system steps the apps use) */
  --sp-1: 4px; --sp-2: 8px; --sp-3: 12px; --sp-4: 16px; --sp-5: 20px; --sp-6: 24px;
  --fs-1: 12px; --fs-2: 13px; --fs-3: 14px; --fs-4: var(--msg-font-size); --fs-5: 18px;
  --radius-pill: 999px;
  --font: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif;
  color-scheme: dark;
}
@media (prefers-color-scheme: light) {
  :root {
${decl(light, XDC_COLOR_TOKENS, "    ")}
    color-scheme: light;
  }
}
`;
}

export const sha256Hex = (buf) => createHash("sha256").update(buf).digest("hex");
export const TRUSTED_PATH = `${root}app/js/trusted-xdc.js`;

/** Existing {hash: name} entries of app/js/trusted-xdc.js (older builds keep working). */
export function readTrusted() {
  if (!existsSync(TRUSTED_PATH)) return {};
  const out = {};
  for (const m of readFileSync(TRUSTED_PATH, "utf8").matchAll(/"([0-9a-f]{64})": "([\w-]+)"/g)) out[m[1]] = m[2];
  return out;
}
export function trustedSource(entries) {
  const lines = Object.entries(entries).map(([h, n]) => `  "${h}": "${n}",`).join("\n");
  return `// Generated by tools/build-builtin-xdc.mjs — do not edit by hand.
// SHA-256 of every Velta-built trusted webxdc bundle (current + earlier
// builds, so call apps already sent to chats keep working). Only an app
// whose .xdc bytes hash to an entry here gets webxdc.veltaCall
// (docs/agents/group-calls.md). The app name, manifest and file name are
// attacker-controlled and never count. KEEP: append-only, never hand-add.
export const TRUSTED_XDC = Object.freeze({
${lines}
});
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const app of XDC_TOKEN_APPS) writeFileSync(`${root}app/webxdc/${app}/velta-tokens.css`, xdcTokensCss());
  const gc = buildGroupCall();
  writeFileSync(`${root}app/builtin/group-call.xdc`, gc);
  const trusted = { ...readTrusted(), [sha256Hex(gc)]: "group-call" };
  writeFileSync(TRUSTED_PATH, trustedSource(trusted));
  console.log(`app/builtin/group-call.xdc ${gc.length} bytes sha256 ${sha256Hex(gc)}`);
  // icon.png is rendered from icon.svg (Velta Beam artwork, see icon.svg).
  const icon = readFileSync(`${root}app/webxdc/send-direct/icon.png`);
  mkdirSync(`${root}app/builtin`, { recursive: true });
  const xdc = buildSendDirect(icon);
  writeFileSync(`${root}app/builtin/send-direct.xdc`, xdc);
  console.log(`app/builtin/send-direct.xdc ${xdc.length} bytes`);
}
