#!/usr/bin/env node
// #334 step 5: generates velta-kmp EmojiData.kt from the REAL app/js/emoji.js
// (the message-sheet tray's named emoji list), so the KMP sheet's "More
// emoji" search matches stable's. tests/kmp-emoji.test.mjs fails CI when the
// committed file is stale.
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "velta-kmp/composeApp/src/commonMain/kotlin/org/velta/kmp/ui/EmojiData.kt");

const esc = (s) => JSON.stringify(s).replace(/\$/g, "\\$");

export async function generateKmpEmoji() {
  const { EMOJI } = await import(pathToFileURL(join(ROOT, "app/js/emoji.js")).href);
  const rows = EMOJI.map((e) => `        ${esc(e.emoji)} to ${esc(e.name)},`).join("\n");
  return `package org.velta.kmp.ui

// GENERATED by tools/gen-kmp-emoji.mjs from app/js/emoji.js — do not
// hand-edit. Stable's named everyday emoji for the message-sheet tray.

internal object EmojiData {
    val EMOJI: List<Pair<String, String>> = listOf(
${rows}
    )

    /** emoji.js searchEmoji: name or glyph contains the trimmed query. */
    fun search(q: String): List<Pair<String, String>> {
        val n = q.trim().lowercase()
        if (n.isEmpty()) return EMOJI
        return EMOJI.filter { (e, name) -> name.contains(n) || e.contains(n) }
    }
}
`;
}

export { OUT };

if (process.env.VELTA_GEN_NO_WRITE !== "1") {
  const body = await generateKmpEmoji();
  writeFileSync(OUT, body);
  console.log(`gen-kmp-emoji: wrote ${OUT}`);
}
